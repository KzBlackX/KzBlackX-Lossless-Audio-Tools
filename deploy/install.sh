#!/usr/bin/env bash
# Install KzBlackX Lossless Audio Tools as a systemd service.
#   sudo DOMAIN=voice.example.com ./install.sh ./kzblackx-audio-linux-amd64
# Without DOMAIN the server speaks plain HTTP on :8080 (microphone access will
# only work on localhost), which is useful behind an existing reverse proxy.
set -euo pipefail

if [[ ${EUID} -ne 0 ]]; then
  echo "请用 root 运行：sudo $0 $*" >&2
  exit 1
fi

SRC=${1:-./kzblackx-audio-linux-amd64}
DOMAIN=${DOMAIN:-}
EMAIL=${EMAIL:-}
PUBLIC_IP=${PUBLIC_IP:-}
PASSWORD=${PASSWORD:-}
ADDR=${ADDR:-:8080}
MAX_ROOM=${MAX_ROOM:-16}
NAME=${NAME:-KzBlackX Lossless Audio Tools}

[[ -f "$SRC" ]] || { echo "找不到二进制：$SRC" >&2; exit 1; }
chmod 0755 "$SRC"

if ! id kzblackx-audio >/dev/null 2>&1; then
  useradd --system --home-dir /var/lib/kzblackx --shell /usr/sbin/nologin --comment "KzBlackX Lossless Audio Tools" kzblackx
fi
install -d -o kzblackx -g kzblackx -m 0750 /var/lib/kzblackx
install -d -o kzblackx -g kzblackx -m 0750 /var/lib/kzblackx/files
install -d -o root -g kzblackx -m 0750 /etc/kzblackx
install -m 0755 "$SRC" /usr/local/bin/kzblackx-audio
install -m 0644 "$(dirname "$0")/kzblackx-audio.service" /etc/systemd/system/kzblackx-audio.service

if [[ -z "$PASSWORD" ]]; then
  PASSWORD=$(openssl rand -hex 16 2>/dev/null || head -c 16 /dev/urandom | od -An -tx1 | tr -d ' \n')
fi
if [[ -z "$PUBLIC_IP" ]]; then
  PUBLIC_IP=$(curl -fsS --max-time 3 http://metadata.tencentyun.com/latest/meta-data/public-ipv4 2>/dev/null || true)
fi
if [[ -z "$PUBLIC_IP" ]]; then
  PUBLIC_IP=$(curl -fsS --max-time 4 https://api.ipify.org 2>/dev/null || true)
fi

if [[ -f /etc/kzblackx/audio.env ]]; then
  echo "保留已有配置：/etc/kzblackx/audio.env"
  KEEP=1
else
  KEEP=0
  {
    echo "# generated by install.sh on $(date -u +%FT%TZ)"
    echo "KZBX_NAME=$NAME"
    echo "KZBX_PASSWORD=$PASSWORD"
    echo "KZBX_PUBLIC_IP=$PUBLIC_IP"
    echo "KZBX_UDP_PORT=3478"
    echo "KZBX_ROOMS=大厅,游戏,音乐"
    echo "KZBX_MAX_ROOM=$MAX_ROOM"
    echo "KZBX_MAX_BITRATE=510"
    echo "KZBX_FILES_DIR=/var/lib/kzblackx/files"
    echo "KZBX_MAX_FILE_MB=100"
    echo "KZBX_FILE_TTL=24h"
    echo "KZBX_ADDR=$ADDR"
    if [[ -n "$DOMAIN" ]]; then
      echo "KZBX_ACME_DOMAIN=$DOMAIN"
      [[ -n "$EMAIL" ]] && echo "KZBX_ACME_EMAIL=$EMAIL"
    fi
    echo "KZBX_TRUST_PROXY=0"
  } > /etc/kzblackx/audio.env
  chown root:kzblackx /etc/kzblackx/audio.env
  chmod 0640 /etc/kzblackx/audio.env
fi

systemctl daemon-reload
systemctl enable --now kzblackx-audio
sleep 1
systemctl --no-pager --lines=0 status kzblackx-audio || true

echo
if [[ "$KEEP" == "0" ]]; then
  echo "服务器密码：$PASSWORD"
fi
echo "公网 IP：${PUBLIC_IP:-未知（请手动填写 KZBX_PUBLIC_IP）}"
if [[ -n "$DOMAIN" ]]; then
  echo "访问地址：https://$DOMAIN"
  echo "别忘了在安全组放行 TCP 80 / 443 与 UDP 3478。"
else
  echo "HTTP 监听：${ADDR}"
  echo "麦克风只在 HTTPS 或 localhost 下可用；公网请配好证书或用反向代理。"
  echo "UDP 3478 必须直连放行（不要走 HTTP 反向代理）。"
fi
